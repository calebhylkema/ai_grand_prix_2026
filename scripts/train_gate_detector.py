#!/usr/bin/env python3
"""Train a YOLOv8-nano keypoint model for gate detection.

Uses the Ultralytics YOLOv8 API to train a pose/keypoint detection model
on synthetic data generated by ``generate_training_data.py``.

Prerequisites::

    pip install ultralytics
    uv run python scripts/generate_training_data.py --num-train 5000 --num-val 500

Usage::

    uv run python scripts/train_gate_detector.py
    uv run python scripts/train_gate_detector.py --data data/gate_keypoints/dataset.yaml --epochs 100

After training, export to ONNX::

    uv run python scripts/train_gate_detector.py --export-only --weights runs/pose/train/weights/best.pt
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

logger = logging.getLogger(__name__)


def train(
    data_yaml: str,
    epochs: int,
    batch_size: int,
    img_size: int,
    model_size: str,
    project: str,
    device: str,
) -> Path:
    """Train a YOLOv8 pose model.

    Parameters
    ----------
    data_yaml : str
        Path to dataset.yaml.
    epochs : int
        Number of training epochs.
    batch_size : int
        Batch size.
    img_size : int
        Input image size.
    model_size : str
        YOLOv8 model size: n, s, m, l, x.
    project : str
        Output project directory.
    device : str
        Training device (e.g., "0" for GPU, "cpu").

    Returns
    -------
    Path
        Path to best weights.
    """
    try:
        from ultralytics import YOLO
    except ImportError:
        logger.error("ultralytics is required. Install with: pip install ultralytics")
        sys.exit(1)

    model_name = f"yolov8{model_size}-pose.pt"
    logger.info("Loading base model: %s", model_name)
    model = YOLO(model_name)

    logger.info("Starting training: %d epochs, batch=%d, imgsz=%d", epochs, batch_size, img_size)
    model.train(
        data=data_yaml,
        epochs=epochs,
        batch=batch_size,
        imgsz=img_size,
        project=project,
        device=device,
        # Keypoint-specific settings
        pose=12.0,  # keypoint loss gain
        # Augmentation (supplement our domain randomisation)
        hsv_h=0.015,
        hsv_s=0.5,
        hsv_v=0.3,
        degrees=15.0,
        translate=0.1,
        scale=0.3,
        flipud=0.0,  # no vertical flip (gates have orientation)
        fliplr=0.0,  # no horizontal flip (corner ordering matters)
        mosaic=0.5,
        mixup=0.1,
    )

    best_weights = Path(project) / "train" / "weights" / "best.pt"
    logger.info("Training complete. Best weights: %s", best_weights)
    return best_weights


def export_onnx(weights_path: str, img_size: int, output_dir: str) -> Path:
    """Export a trained model to ONNX format.

    Parameters
    ----------
    weights_path : str
        Path to .pt weights file.
    img_size : int
        Input image size.
    output_dir : str
        Directory for the ONNX file.

    Returns
    -------
    Path
        Path to exported ONNX model.
    """
    try:
        from ultralytics import YOLO
    except ImportError:
        logger.error("ultralytics is required. Install with: pip install ultralytics")
        sys.exit(1)

    model = YOLO(weights_path)
    logger.info("Exporting %s to ONNX (imgsz=%d)", weights_path, img_size)

    model.export(
        format="onnx",
        imgsz=img_size,
        simplify=True,
        opset=17,
    )

    # Ultralytics saves ONNX next to the .pt file
    onnx_path = Path(weights_path).with_suffix(".onnx")

    # Copy to output directory
    out_path = Path(output_dir) / "gate_keypoint.onnx"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    import shutil

    shutil.copy2(onnx_path, out_path)
    logger.info("ONNX model saved to %s", out_path)
    return out_path


def main() -> None:
    """CLI entry point."""
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(name)s %(levelname)s %(message)s",
        datefmt="%H:%M:%S",
    )

    parser = argparse.ArgumentParser(description="Train YOLOv8 gate keypoint detector.")
    parser.add_argument(
        "--data",
        type=str,
        default="data/gate_keypoints/dataset.yaml",
        help="Path to dataset.yaml",
    )
    parser.add_argument("--epochs", type=int, default=50, help="Training epochs")
    parser.add_argument("--batch", type=int, default=16, help="Batch size")
    parser.add_argument("--imgsz", type=int, default=640, help="Input image size")
    parser.add_argument(
        "--model-size",
        type=str,
        default="n",
        choices=["n", "s", "m", "l", "x"],
        help="YOLOv8 model size (n=nano, s=small, etc.)",
    )
    parser.add_argument("--project", type=str, default="runs/pose", help="Output project dir")
    parser.add_argument("--device", type=str, default="0", help="Device (0=GPU, cpu)")
    parser.add_argument(
        "--export-only",
        action="store_true",
        help="Skip training, only export existing weights to ONNX",
    )
    parser.add_argument(
        "--weights",
        type=str,
        default="",
        help="Path to .pt weights (for --export-only)",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="models",
        help="Directory for exported ONNX model",
    )
    args = parser.parse_args()

    if args.export_only:
        if not args.weights:
            logger.error("--weights is required with --export-only")
            sys.exit(1)
        export_onnx(args.weights, args.imgsz, args.output_dir)
    else:
        best = train(
            data_yaml=args.data,
            epochs=args.epochs,
            batch_size=args.batch,
            img_size=args.imgsz,
            model_size=args.model_size,
            project=args.project,
            device=args.device,
        )
        logger.info("To export to ONNX, run:")
        logger.info(
            "  uv run python scripts/train_gate_detector.py --export-only --weights %s", best
        )


if __name__ == "__main__":
    main()
